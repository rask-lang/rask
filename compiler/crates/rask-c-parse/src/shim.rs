//! Wrappers for a header's `static inline` functions (struct.c-interop/IN2).
//!
//! An inline function has no symbol to link to: C emits its body only inside
//! the files that use it. The wrapper is one of those files, with a real
//! function per inline that calls it. Its signatures come from the header
//! itself, so a binding needs to say nothing but which header.

use crate::{CDecl, CFuncDecl, CItem, CType};

/// The symbol Rask links to for inline function `name`.
pub fn wrapper_symbol(name: &str) -> String {
    format!("rask_inline_{}", name)
}

/// C source defining a wrapper for each of `names` that `items` declares
/// inline, and the names it found no inline declaration for.
pub fn wrapper_source(header: &str, items: &[CItem], names: &[String]) -> (String, Vec<String>) {
    let mut out = format!("/* Generated by rask: wrappers for the inline functions of {} */\n", header);
    out.push_str(&format!("#include \"{}\"\n\n", header.replace('\\', "\\\\").replace('"', "\\\"")));
    let mut missing = Vec::new();
    for name in names {
        let found = items.iter().find_map(|i| match &i.decl {
            CDecl::Function(f) if &f.name == name && f.is_inline => Some(f),
            _ => None,
        });
        match found {
            Some(f) => out.push_str(&wrapper(f)),
            None => missing.push(name.clone()),
        }
    }
    (out, missing)
}

fn wrapper(f: &CFuncDecl) -> String {
    let no_params = f.params.is_empty() || (f.params.len() == 1 && f.params[0].ty == CType::Void);
    let (params, args) = if no_params {
        ("void".to_string(), String::new())
    } else {
        let ps: Vec<String> = f.params.iter().enumerate().map(|(i, p)| declare(&p.ty, &format!("a{}", i))).collect();
        let args: Vec<String> = (0..f.params.len()).map(|i| format!("a{}", i)).collect();
        (ps.join(", "), args.join(", "))
    };
    let head = declare(&f.ret_ty, &format!("{}({})", wrapper_symbol(&f.name), params));
    let call = format!("{}({})", f.name, args);
    if strip(&f.ret_ty) == &CType::Void {
        format!("{} {{ {}; }}\n", head, call)
    } else {
        format!("{} {{ return {}; }}\n", head, call)
    }
}

fn strip(t: &CType) -> &CType {
    match t {
        CType::Const(inner) => strip(inner),
        other => other,
    }
}

/// `ty` declaring `name`, as C spells it: the declarator wraps the name, so
/// `int (*cb)(void *)` and `char *names[4]` come out inside-out.
pub fn declare(ty: &CType, name: &str) -> String {
    match ty {
        CType::Const(inner) => match &**inner {
            CType::Pointer(p) => pointer(p, &format!("const {}", name)),
            other => format!("const {}", declare(other, name)),
        },
        CType::Pointer(inner) => pointer(inner, name),
        CType::Array(elem, n) => {
            let len = n.map(|n| n.to_string()).unwrap_or_default();
            declare(elem, &format!("{}[{}]", name, len))
        }
        CType::FuncPtr { ret, params, is_variadic } => {
            let mut ps: Vec<String> = params.iter().map(|p| declare(p, "")).collect();
            if *is_variadic {
                ps.push("...".into());
            }
            if ps.is_empty() {
                ps.push("void".into());
            }
            declare(ret, &format!("(*{})({})", name, ps.join(", ")))
        }
        base => {
            let b = base_name(base);
            if name.is_empty() { b } else { format!("{} {}", b, name) }
        }
    }
}

fn pointer(inner: &CType, name: &str) -> String {
    match strip(inner) {
        // A pointer to a function pointer: the function pointer's own `(*…)`.
        CType::FuncPtr { .. } => declare(inner, &format!("*{}", name)),
        CType::Array(..) => declare(inner, &format!("(*{})", name)),
        _ => declare(inner, &format!("*{}", name)),
    }
}

fn base_name(t: &CType) -> String {
    match t {
        CType::Void => "void".into(),
        CType::Char => "char".into(),
        CType::SignedChar => "signed char".into(),
        CType::UnsignedChar => "unsigned char".into(),
        CType::Short => "short".into(),
        CType::UnsignedShort => "unsigned short".into(),
        CType::Int => "int".into(),
        CType::UnsignedInt => "unsigned int".into(),
        CType::Long => "long".into(),
        CType::UnsignedLong => "unsigned long".into(),
        CType::LongLong => "long long".into(),
        CType::UnsignedLongLong => "unsigned long long".into(),
        CType::Float => "float".into(),
        CType::Double => "double".into(),
        CType::Bool => "_Bool".into(),
        CType::SizeT => "size_t".into(),
        CType::SSizeT => "ptrdiff_t".into(),
        CType::FixedInt { bits, signed } => format!("{}int{}_t", if *signed { "" } else { "u" }, bits),
        CType::IntPtr { signed } => (if *signed { "intptr_t" } else { "uintptr_t" }).into(),
        CType::Named(n) => n.clone(),
        CType::StructTag(t) => format!("struct {}", t),
        CType::UnionTag(t) => format!("union {}", t),
        CType::EnumTag(t) => format!("enum {}", t),
        // Reached only through `declare`, which handles these itself.
        CType::Const(_) | CType::Pointer(_) | CType::Array(..) | CType::FuncPtr { .. } => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declarators_come_out_inside_out() {
        let int = || Box::new(CType::Int);
        assert_eq!(declare(&CType::Pointer(Box::new(CType::Const(Box::new(CType::Char)))), "s"), "const char *s");
        assert_eq!(declare(&CType::Array(Box::new(CType::Pointer(Box::new(CType::Char))), Some(4)), "names"), "char *names[4]");
        let cb = CType::FuncPtr { ret: int(), params: vec![CType::Pointer(Box::new(CType::Void))], is_variadic: false };
        assert_eq!(declare(&cb, "cb"), "int (*cb)(void *)");
        assert_eq!(declare(&CType::Const(Box::new(CType::Pointer(int()))), "p"), "int *const p");
    }

    #[test]
    fn a_wrapper_per_inline() {
        let parsed = crate::parse_c_header(
            "typedef struct { int x, y; } P;\nstatic inline int twice(int n) { return n * 2; }\nstatic inline void touch(P *p) { p->x = 1; }\n",
        )
        .unwrap();
        let (src, missing) = wrapper_source("lib.h", &parsed.decls, &["twice".into(), "touch".into(), "nope".into()]);
        assert!(src.contains("#include \"lib.h\""), "{}", src);
        assert!(src.contains("int rask_inline_twice(int a0) { return twice(a0); }"), "{}", src);
        assert!(src.contains("void rask_inline_touch(P *a0) { touch(a0); }"), "{}", src);
        assert_eq!(missing, vec!["nope".to_string()]);
    }
}
