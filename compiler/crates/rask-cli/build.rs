//! Bakes the C runtime sources into the binary.
//!
//! A released `rask` is a single file with no repo around it, so the on-disk
//! search in `find_runtime_dir` finds nothing and every native compile fails at
//! link. The sources travel inside the binary instead, and get written to a
//! cache directory the first time one is needed.
//!
//! The list is read from the directory, never written down — a hand-maintained
//! listing is what made #1041, where a source added to the tree wasn't added to
//! the constant and every binary built in between linked a `string.c` calling
//! into a file it had never heard of.

use std::path::{Path, PathBuf};

fn main() {
    // Without this, changing RASK_RUNTIME_DIR leaves the previously baked
    // runtime in place and says nothing — a stale runtime is worse than a
    // build error, because nothing points at it.
    println!("cargo:rerun-if-env-changed=RASK_RUNTIME_DIR");

    let runtime_dir = runtime_dir();

    // Subdirectories too: `core-math/` keeps the vendored math library in its
    // upstream shape. A source is keyed by its path relative to the runtime
    // directory, so `link.rs` writes it back to the same place.
    let mut sources: Vec<PathBuf> = Vec::new();
    collect(&runtime_dir, &mut sources);
    sources.sort();

    if sources.is_empty() {
        panic!("no runtime sources in {} — runtime is incomplete", runtime_dir.display());
    }

    let mut out = String::from(
        "// @generated by build.rs — the runtime sources, keyed by path in the runtime directory.\n\
         pub static EMBEDDED_RUNTIME: &[(&str, &str)] = &[\n",
    );
    for path in &sources {
        // Rebuild when a source's contents change, not just when the directory
        // gains or loses an entry.
        println!("cargo:rerun-if-changed={}", path.display());
        let name = path
            .strip_prefix(&runtime_dir)
            .unwrap()
            .to_str()
            .unwrap()
            .replace(std::path::MAIN_SEPARATOR, "/");
        out.push_str(&format!(
            "    ({:?}, include_str!({:?})),\n",
            name,
            path.display().to_string()
        ));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("embedded_runtime.rs");
    std::fs::write(&dest, out).expect("write embedded_runtime.rs");
}

/// Every `.c` and `.h` under `dir`. A directory is watched as well as its
/// files, so a source added to `core-math/` reruns the script.
fn collect(dir: &Path, out: &mut Vec<PathBuf>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let entries = std::fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("cannot read runtime dir {}: {e}", dir.display()));
    for path in entries.flatten().map(|e| e.path()) {
        if path.is_dir() {
            collect(&path, out);
        } else if matches!(path.extension().and_then(|s| s.to_str()), Some("c") | Some("h")) {
            out.push(path);
        }
    }
}

/// The runtime lives at `compiler/runtime`, two levels up from this crate.
/// `RASK_RUNTIME_DIR` overrides it so a build can point at a runtime elsewhere.
///
/// Always absolute. The paths go into `include_str!` in a file written to
/// `OUT_DIR`, and that macro resolves a relative path against the directory of
/// the file holding it — not against the build script's working directory. So a
/// relative `RASK_RUNTIME_DIR=../../runtime` passes the `exists()` check here
/// (cwd is the crate root) and then fails to compile as
/// `OUT_DIR/../../runtime/alloc.c`.
fn runtime_dir() -> PathBuf {
    if let Ok(dir) = std::env::var("RASK_RUNTIME_DIR") {
        let p = PathBuf::from(dir);
        if p.join("runtime.c").exists() {
            return absolute(&p);
        }
        panic!("RASK_RUNTIME_DIR is set but has no runtime.c: {}", p.display());
    }

    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let candidate = Path::new(&manifest).join("../../runtime");
    if candidate.join("runtime.c").exists() {
        return absolute(&candidate);
    }
    panic!("no runtime next to {} — expected ../../runtime", manifest.display());
}

fn absolute(p: &Path) -> PathBuf {
    p.canonicalize()
        .unwrap_or_else(|e| panic!("cannot resolve runtime dir {}: {e}", p.display()))
}
