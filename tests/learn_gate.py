"""The tutorial gate: tests/learn_gate.sh runs this.

The tutorial in docs/book/src/learn/ is one program, the MUD in mud/, and
chapters that show it. Three things there can drift from the compiler, and
this checks each:

1. Exercise files. A chapter's exercise file is the program so far with some
   function bodies replaced by `todo()`. It's generated, never written, so
   the exercise and the program it comes from can't disagree. A function is
   marked with the task statement on the lines above it:

       // exercise 06: Find the room with this name, or none.
       public func room(self, name: string) -> Link<Room>? {

   `exercises` lists the files, relative to the tutorial directory, that make
   up each exercise file. Most are the MUD's; the first chapters also use
   early/, the version of the world they build before chapter 11 replaces it:

       06-holding-many-things.rk: mud/direction.rk early/world.rk

   A committed exercise file that differs from what its files generate is
   stale, and so is one with no line in `exercises`. Every exercise file has
   to pass `rask check`, and the same files with no body replaced, which is
   the solution, have to pass their tests on both backends. So does every
   package in the tutorial (mud/), whole, since the exercises use only some
   of its files.

2. Chapters read as raw Markdown, since offline that's all a reader has. So
   no `{{#include}}`: a block that shows a file says `<!-- from: path -->`
   instead, and the book gate checks it's a verbatim run of that file.

3. The shell commands in the chapters (`bash`, `sh` or `shell` blocks) run,
   in chapter order, in a copy of the tutorial directory, with the built
   `rask` first on PATH and `bash -e`, so any failing line counts. The first
   `<!-- from: output/x.out -->` block after a command, before the next one,
   is its output, and the command has to print what that file holds; one
   with no output block has to exit 0. A file in output/ that no command
   prints is stale. A block marked `<!-- learn: skip -->` isn't run (the
   install line). Durations print as `(0ms)`, so a pinned output doesn't
   change with the machine.

`--update` regenerates exercise files and pinned outputs, and fills in an
output block in a chapter that is empty or showed the whole of the old output.

Usage: learn_gate.py [--update] <learn-dir> <rask-binary>
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile

MARK = re.compile(r"^(\s*)// exercise (\d+):")
FUNC = re.compile(r"^(\s*)(public\s+)?func\s+\w+")
FENCE = re.compile(r"^(```+)\s*(.*)$")
# The line that closes a function body, at the function's indentation.
CLOSE = re.compile(r"^\}\s*(//.*)?$")
# Fences whose blocks are commands to run.
SHELLS = ("bash", "sh", "shell")
FROM = re.compile(r"^<!--\s*from:\s*(\S+)\s*-->\s*$")
SKIP = "<!-- learn: skip -->"
GENERATED = (
    "// Generated by `tests/learn_gate.sh --update` from the files `exercises` lists. Edit those, not this.\n"
    "// test-specs: skip: an exercise starts with its tests failing\n"
)


class Gate:
    def __init__(self, learn, rask, update):
        self.learn = learn
        self.rask = rask
        self.update = update
        self.fails = []
        self.ok = 0
        self.marked = 0

    def fail(self, msg):
        self.fails.append(msg)

    # ── 1. Exercise files ─────────────────────────────────────────────────

    def manifest(self):
        path = os.path.join(self.learn, "exercises")
        if not os.path.isfile(path):
            return {}
        out = {}
        for n, line in enumerate(open(path).read().split("\n"), 1):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            name, _, mods = line.partition(":")
            m = re.match(r"(\d+)-[\w-]+\.rk$", name.strip())
            if not m:
                self.fail(f"exercises:{n}: `{name.strip()}` isn't `NN-name.rk`")
                continue
            if name.strip() in out:
                self.fail(f"exercises:{n}: {name.strip()} is listed twice")
                continue
            out[name.strip()] = (m.group(1), mods.split())
        return out

    def module(self, name):
        path = os.path.join(self.learn, name)
        if not os.path.isfile(path):
            return None
        return open(path).read().split("\n")

    def generate(self, number, modules, solved=False):
        imports, bodies = [], []
        for name in modules:
            lines = self.module(name)
            if lines is None:
                self.fail(f"exercises: names {name}, which isn't there")
                return None
            body = lines if solved else self.todo(lines, number)
            # The SPDX line and the imports go once, at the top.
            kept = []
            for line in body:
                if line.startswith("// SPDX-License-Identifier"):
                    continue
                if line.startswith("import "):
                    if line not in imports:
                        imports.append(line)
                    continue
                kept.append(line)
            while kept and not kept[0].strip():
                kept.pop(0)
            bodies.append(f"// ── {name} " + "─" * max(0, 64 - len(name)) + "\n\n" + "\n".join(kept).rstrip() + "\n")
        head = "// SPDX-License-Identifier: (MIT OR Apache-2.0)\n" + GENERATED + "\n"
        if imports:
            head += "\n".join(imports) + "\n\n"
        return head + "\n".join(bodies)

    def todo(self, lines, number):
        """`lines` with the bodies of the functions marked for `number` replaced."""
        out, i = [], 0
        while i < len(lines):
            m = MARK.match(lines[i])
            if not m or m.group(2) != number:
                out.append(lines[i])
                i += 1
                continue
            # The task statement is the marker and the comments under it.
            while i < len(lines) and lines[i].strip().startswith("//"):
                out.append(lines[i])
                i += 1
            if i >= len(lines) or not FUNC.match(lines[i]) or not lines[i].rstrip().endswith("{"):
                self.fail(f"exercise {number}: a marker isn't followed by a `func … {{` line")
                return lines
            indent = FUNC.match(lines[i]).group(1)
            out.append(lines[i])
            i += 1
            # The body ends at the first line back at the function's own
            # indentation, which `rask fmt` makes its closing brace. Anything
            # else there means the indentation can't be trusted to say.
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(indent + " ")):
                i += 1
            if i >= len(lines) or not CLOSE.match(lines[i][len(indent):]):
                self.fail(f"exercise {number}: a marked function's body doesn't end in a `}}` at the function's own indentation")
                return lines
            self.marked += 1
            out.append(indent + "    todo()")
            out.append(lines[i])
            i += 1
        return out

    def markers(self):
        """(number, file) for every marker in the tutorial's subdirectories."""
        found = []
        for sub in sorted(os.listdir(self.learn)):
            top = os.path.join(self.learn, sub)
            if not os.path.isdir(top) or sub in ("build", "output"):
                continue
            for dirpath, dirs, files in os.walk(top):
                dirs[:] = sorted(d for d in dirs if d != "build")
                for f in sorted(files):
                    if f.endswith(".rk"):
                        path = os.path.join(dirpath, f)
                        for line in open(path).read().split("\n"):
                            m = MARK.match(line)
                            if m:
                                found.append((m.group(2), os.path.relpath(path, self.learn)))
        return found

    def exercises(self):
        manifest = self.manifest()
        for number, module in self.markers():
            if not any(n == number and module in mods for n, mods in manifest.values()):
                self.fail(f"{module} marks a function for exercise {number}, and no exercise {number} in `exercises` uses it")
        committed = {f for f in os.listdir(self.learn) if re.match(r"\d+-[\w-]+\.rk$", f)}
        for name in sorted(committed - set(manifest)):
            self.fail(f"{name} isn't in `exercises`: delete it, or list what it's made of")
        for name, (number, modules) in sorted(manifest.items()):
            self.marked = 0
            before = len(self.fails)
            text = self.generate(number, modules)
            if text is None or len(self.fails) > before:
                continue
            if self.marked == 0:
                self.fail(f"{name}: no function in {', '.join(modules)} is marked `// exercise {number}:`, so the exercise would be the finished program")
                continue
            path = os.path.join(self.learn, name)
            if self.update:
                open(path, "w").write(text)
                print(f"updated: {name}")
            elif not os.path.isfile(path) or open(path).read() != text:
                self.fail(f"{name} is stale: the MUD has changed since it was generated (run with --update)")
                continue
            r = subprocess.run([self.rask, "check", path], capture_output=True, text=True)
            if r.returncode != 0:
                errors = [l for l in (r.stdout + r.stderr).split("\n") if l.startswith("error")]
                self.fail(f"{name} doesn't pass `rask check`: {'; '.join(errors[:3])}")
                continue
            if self.solution_passes(name, number, modules):
                self.ok += 1

    def solution_passes(self, name, number, modules):
        """The exercise's files as they are, the solution, pass on both backends."""
        text = self.generate(number, modules, solved=True)
        work = tempfile.mkdtemp(prefix="learn_solution_")
        try:
            path = os.path.join(work, name)
            open(path, "w").write(text)
            has_tests = any(re.match(r"\s*test \"", l) for l in text.split("\n"))
            runs = [["test"], ["test", "--interp"]] if has_tests else [["check"]]
            for args in runs:
                r = subprocess.run([self.rask, *args, path], capture_output=True, text=True, timeout=600)
                if r.returncode != 0:
                    last = [l for l in (r.stdout + r.stderr).split("\n") if l.strip()][-6:]
                    self.fail(f"{name}: the solution fails `rask {' '.join(args)}`:\n" + indent("\n".join(last)))
                    return False
            return True
        finally:
            shutil.rmtree(work, ignore_errors=True)

    def packages(self):
        """Every package in the tutorial passes its tests on both backends.

        The exercises only compile the files they list, so without this the
        rest of the MUD (the server, saving, the maze) is checked by nothing.
        """
        for dirpath, dirs, files in os.walk(self.learn):
            dirs[:] = sorted(d for d in dirs if d not in ("build", "output"))
            if "rask.toml" not in files:
                continue
            rel = os.path.relpath(dirpath, self.learn)
            failed = False
            for args in (["test"], ["test", "--interp"]):
                r = subprocess.run([self.rask, *args, dirpath], capture_output=True, text=True, timeout=900)
                if r.returncode != 0:
                    last = [l for l in (r.stdout + r.stderr).split("\n") if l.strip()][-6:]
                    self.fail(f"{rel}/ fails `rask {' '.join(args)}`:\n" + indent("\n".join(last)))
                    failed = True
                    break
            if not failed:
                self.ok += 1

    # ── 2 and 3. Chapters ─────────────────────────────────────────────────

    def chapters(self):
        return sorted(f for f in os.listdir(self.learn) if f.endswith(".md"))

    def fences(self, lines):
        """(open line, info word, body start, close line) for each fenced block."""
        out, i = [], 0
        while i < len(lines):
            m = FENCE.match(lines[i])
            if not m:
                i += 1
                continue
            ticks, info = m.group(1), m.group(2).split()
            j = i + 1
            while j < len(lines) and lines[j].rstrip() != ticks:
                j += 1
            out.append((i, info[0] if info else "", i + 1, j))
            i = j + 1
        return out

    def commands(self, md):
        """(line, script, output path or None, output block span) per shell block.

        A command's output block is the first `from:` block after it and
        before the next command, prose in between or not.
        """
        lines = open(os.path.join(self.learn, md)).read().split("\n")
        fences = self.fences(lines)
        out = []
        for n, (open_, info, start, close) in enumerate(fences):
            if info not in SHELLS:
                continue
            skipped = open_ > 0 and lines[open_ - 1].strip() == SKIP
            output, span = None, None
            for o_open, o_info, o_start, o_close in fences[n + 1:]:
                if o_info in SHELLS:
                    break
                m = FROM.match(lines[o_open - 1]) if o_open > 0 else None
                if m and m.group(1).startswith("output/"):
                    output, span = m.group(1), (o_start, o_close)
                    break
            if not skipped:
                out.append((open_ + 1, "\n".join(lines[start:close]), output, span))
        return out

    def run_chapters(self):
        for md in self.chapters():
            text = open(os.path.join(self.learn, md)).read()
            if re.search(r"(?<!\\){{#include", text):
                self.fail(f"{md} uses {{{{#include}}}}, which a reader of the raw file sees as a directive: show the code with `<!-- from: path -->` instead")
        work = tempfile.mkdtemp(prefix="learn_gate_")
        try:
            copy = os.path.join(work, "learn")
            shutil.copytree(self.learn, copy, ignore=shutil.ignore_patterns("build"))
            bindir = os.path.join(work, "bin")
            os.mkdir(bindir)
            os.symlink(os.path.abspath(self.rask), os.path.join(bindir, "rask"))
            env = dict(os.environ, PATH=bindir + os.pathsep + os.environ.get("PATH", ""), NO_COLOR="1")
            produced = set()
            for md in self.chapters():
                # Read again after each command: --update can fill in an
                # output block, which moves everything below it.
                n = 0
                while n < len(self.commands(md)):
                    line, script, output, span = self.commands(md)[n]
                    self.run_one(md, line, script, output, span, copy, env)
                    if output:
                        produced.add(os.path.normpath(output))
                    n += 1
            outdir = os.path.join(self.learn, "output")
            if os.path.isdir(outdir):
                for name in sorted(os.listdir(outdir)):
                    if os.path.normpath(os.path.join("output", name)) not in produced:
                        self.fail(f"output/{name} isn't what any command in a chapter prints: delete it, or put its block after the command")
        finally:
            shutil.rmtree(work, ignore_errors=True)

    def run_one(self, md, line, script, output, span, copy, env):
        r = subprocess.run(["bash", "-e", "-o", "pipefail", "-c", script], cwd=copy, env=env,
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=600)
        got = r.stdout.replace(copy + "/", "").replace(copy, ".")
        got = re.sub(r"\(\d+(\.\d+)?m?s\)", "(0ms)", got)
        got = "\n".join(l.rstrip() for l in got.rstrip().split("\n")) + "\n"
        where = f"{md}:{line}"
        if output is None:
            if r.returncode != 0:
                self.fail(f"{where}: the command exits {r.returncode}, and no output block says it should fail:\n" + indent(got))
            else:
                self.ok += 1
            return
        pinned = os.path.join(self.learn, output)
        if self.update:
            self.rewrite(md, span, pinned, got)
            os.makedirs(os.path.dirname(pinned), exist_ok=True)
            open(pinned, "w").write(got)
            print(f"updated: {output}")
            self.ok += 1
            return
        if not os.path.isfile(pinned):
            self.fail(f"{where}: {output} isn't there (run with --update)")
        elif open(pinned).read() != got:
            self.fail(f"{where}: the command printed something else than {output}:\n" + indent(got))
        else:
            self.ok += 1

    def rewrite(self, md, span, pinned, new):
        """Put the new output in the chapter, when the block is empty or showed
        all of the old."""
        path = os.path.join(self.learn, md)
        lines = open(path).read().split("\n")
        start, end = span
        old = open(pinned).read().rstrip("\n").split("\n") if os.path.isfile(pinned) else None
        if start != end and lines[start:end] != old:
            return
        lines[start:end] = new.rstrip("\n").split("\n")
        open(path, "w").write("\n".join(lines))


def indent(text):
    return "\n".join("    " + l for l in text.rstrip().split("\n")[:20])


def main(argv):
    update = "--update" in argv
    args = [a for a in argv if a != "--update"]
    if len(args) != 2:
        print(__doc__.strip().split("\n")[-1], file=sys.stderr)
        return 2
    gate = Gate(args[0], args[1], update)
    gate.exercises()
    gate.packages()
    gate.run_chapters()
    for f in gate.fails:
        print(f"FAIL: {f}")
    print("──────────────────────────────────────────────────")
    print(f"learn gate: {gate.ok} ok, {len(gate.fails)} failed")
    return 1 if gate.fails else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
