#!/usr/bin/env node
// SPDX-License-Identifier: (MIT OR Apache-2.0)
//
// Builds /blog/ from the markdown in writing/.
//
// The markdown is rendered by examples/markdown_renderer.rk — the repo's own
// Rask program, run through the compiler the repo builds. The site is the one
// place where using the language for something real costs nothing extra, and
// it already paid: pointing it at a post found a byte-slicing bug that a page
// with an em-dash in it triggered every time.
//
// Posts stay in writing/ as plain markdown. GitHub renders them there, the book
// gate checks their code blocks, and this turns them into pages.

const fs = require('fs').promises;
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '../..');
const POSTS_DIR = path.join(ROOT, 'writing');
const OUT_DIR = path.join(ROOT, 'docs/build/blog');
const RENDERER = path.join(ROOT, 'examples/markdown_renderer.rk');

function rask() {
    for (const profile of ['release', 'debug']) {
        const bin = path.join(ROOT, 'compiler/target', profile, 'rask');
        try {
            require('fs').accessSync(bin);
            return bin;
        } catch (e) { /* try the next one */ }
    }
    throw new Error('no rask binary — build it with `cargo build --release -p rask-cli`');
}

/// Title and date, read off the post itself rather than from front matter.
///
/// The posts are written to be read on GitHub too, so they carry no metadata
/// block: the title is the `# heading` and the date is the `*Written …*` line
/// under it. What the author already writes is the metadata.
function meta(source, slug) {
    const title = (source.match(/^#\s+(.+)$/m) || [, slug])[1].trim();
    const written = (source.match(/^\*Written\s+(\d{4}-\d{2}-\d{2})/m) || [])[1] || null;
    const updated = (source.match(/^\*Updated\s+(\d{4}-\d{2}-\d{2})/m) || [])[1] || null;

    // The first paragraph that isn't the title or a date line, for the index.
    const standfirst = source
        .split('\n\n')
        .map(p => p.trim())
        .find(p => p && !p.startsWith('#') && !p.startsWith('*') && !p.startsWith('<!--'));

    return { title, written, updated, standfirst: standfirst || '' };
}

const escape = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const readable = iso => new Date(iso + 'T00:00:00Z').toLocaleDateString('en-GB', {
    day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC',
});

function page({ title, description, body, canonical }) {
    return `<!-- SPDX-License-Identifier: (MIT OR Apache-2.0) -->
<!-- Generated by docs/blog/build.js from writing/*.md — edit the markdown. -->
<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${escape(title)}</title>
<meta name="description" content="${escape(description)}">
<meta property="og:title" content="${escape(title)}">
<meta property="og:description" content="${escape(description)}">
<meta property="og:type" content="article">
<link rel="canonical" href="https://rask-lang.dev${canonical}">
<link rel="icon" type="image/png" href="/book/assets/rask32.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Newsreader:opsz,wght@6..72,400;6..72,500;6..72,600&family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="/tokens.css">
<link rel="stylesheet" href="/blog/blog.css">
</head>
<body>

<header class="page masthead">
    <a class="brand" href="/">
        <img src="/book/assets/rask48.png" alt="">
        rask
    </a>
    <nav>
        <a href="/book/">Docs</a>
        <a href="/app/">Playground</a>
        <a href="/blog/">Blog</a>
        <a href="https://github.com/rask-lang/rask">GitHub</a>
    </nav>
</header>

${body}

<footer class="page">
    <nav>
        <a href="/">Home</a>
        <a href="/book/">Docs</a>
        <a href="/app/">Playground</a>
        <a href="https://github.com/rask-lang/rask">GitHub</a>
    </nav>
    <span>MIT or Apache-2.0, your choice.</span>
</footer>

</body>
</html>
`;
}

async function build() {
    const bin = rask();
    await fs.mkdir(OUT_DIR, { recursive: true });

    const files = (await fs.readdir(POSTS_DIR))
        .filter(f => f.endsWith('.md') && f !== 'README.md');

    const posts = [];
    for (const file of files) {
        const slug = path.basename(file, '.md');
        const source = await fs.readFile(path.join(POSTS_DIR, file), 'utf-8');
        const info = meta(source, slug);

        // The bare `*Written …*` line comes out of the body: the page shows the
        // date as a `<time>` in its own dateline, and printing it twice under
        // the title reads like a mistake. It stays in the markdown because
        // that's what dates the post on GitHub, where there is no template.
        // An `*Updated …*` line says more than a date, so it stays.
        const forWeb = source.replace(/^\*Written\s+\d{4}-\d{2}-\d{2}\.?\*\s*$/m, '');
        const staged = path.join(OUT_DIR, `.${slug}.md`);
        await fs.writeFile(staged, forWeb, 'utf-8');

        const html = execFileSync(bin, [
            'run', RENDERER, '--', '--fragment', '--stdout', staged,
        ], { encoding: 'utf-8', cwd: ROOT });
        await fs.unlink(staged);

        if (html.includes('panic at')) {
            throw new Error(`renderer failed on ${file}:\n${html}`);
        }

        posts.push({ slug, ...info, html });
        console.log(`  - ${file} -> /blog/${slug}/  (${info.written || 'undated'})`);
    }

    // Newest first. An undated post sorts last rather than first, so a missing
    // date can't quietly take the top of the page.
    posts.sort((a, b) => (b.written || '').localeCompare(a.written || ''));

    for (const post of posts) {
        const dated = post.written
            ? `<p class="dateline"><time datetime="${post.written}">${readable(post.written)}</time>${
                post.updated ? ` · updated ${readable(post.updated)}` : ''}</p>`
            : '';
        const body = `<main class="page post">
<p class="back"><a href="/blog/">← all posts</a></p>
${dated}
${post.html.trim()}
</main>`;
        await fs.mkdir(path.join(OUT_DIR, post.slug), { recursive: true });
        await fs.writeFile(
            path.join(OUT_DIR, post.slug, 'index.html'),
            page({ title: `${post.title} · Rask`, description: post.standfirst.slice(0, 200),
                   body, canonical: `/blog/${post.slug}/` }),
            'utf-8');
    }

    const list = posts.map(p => `        <li>
            <a href="/blog/${p.slug}/">${escape(p.title)}</a>
            ${p.written ? `<time datetime="${p.written}">${readable(p.written)}</time>` : ''}
        </li>`).join('\n');

    const index = `<main class="page blog-index">
    <h1>Blog</h1>
    <p class="lede">Longer pieces about why Rask is shaped the way it is. Each is
    dated and left as written &mdash; where a decision has changed since, the post says so.</p>
    <ul class="posts">
${list}
    </ul>
</main>`;

    await fs.writeFile(path.join(OUT_DIR, 'index.html'),
        page({ title: 'Blog · Rask', description: 'Longer pieces about why Rask is shaped the way it is.',
               body: index, canonical: '/blog/' }), 'utf-8');

    await fs.copyFile(path.join(__dirname, 'blog.css'), path.join(OUT_DIR, 'blog.css'));
    console.log(`\nGenerated ${OUT_DIR}\n   ${posts.length} posts`);
}

build().catch(err => {
    console.error('Error building blog:', err.message);
    process.exit(1);
});
